"""ExperimentRepository — coordinator's view of submitted experiments.

`experiment_id` is generated by the coordinator on insert (`exp-<random>`).
Two tenants can reuse the same `tenant_experiment_label` without collision;
the coordinator's ID disambiguates everywhere.

Status transitions enforced at the repository level (the route layer can do
additional credential-based authorization). Invalid transitions raise
`InvalidStatusTransitionError`.

Allowed transitions:
  submitted → approved, aborted
  approved  → paused, aborted, completed
  paused    → approved, aborted
  aborted   → archived
  completed → archived
  archived  → (terminal)
"""

from __future__ import annotations

import secrets
import sqlite3
from datetime import UTC, datetime

from auspexai_platform.auth.credential import CredentialClass
from auspexai_platform.db.database import Database
from auspexai_platform.db.models import Experiment, ExperimentStatus, IntegrityPolicy


class DuplicateExperimentLabelError(Exception):
    """Raised when a tenant tries to register two experiments with the same
    `tenant_experiment_label`."""


class ExperimentNotFoundError(Exception):
    """Raised when an experiment_id does not match any row."""


class InvalidStatusTransitionError(Exception):
    """Raised when a status update would violate the allowed transition graph."""


ALLOWED_TRANSITIONS: dict[ExperimentStatus, set[ExperimentStatus]] = {
    ExperimentStatus.SUBMITTED: {ExperimentStatus.APPROVED, ExperimentStatus.ABORTED},
    ExperimentStatus.APPROVED: {
        ExperimentStatus.PAUSED,
        ExperimentStatus.ABORTED,
        ExperimentStatus.COMPLETED,
    },
    ExperimentStatus.PAUSED: {ExperimentStatus.APPROVED, ExperimentStatus.ABORTED},
    ExperimentStatus.ABORTED: {ExperimentStatus.ARCHIVED},
    ExperimentStatus.COMPLETED: {ExperimentStatus.ARCHIVED},
    ExperimentStatus.ARCHIVED: set(),
}


def _generate_experiment_id() -> str:
    """Coordinator-side ID: `exp-<random 8 chars>`. ~48 bits of randomness;
    collision probability negligible for any realistic experiment count."""
    return f"exp-{secrets.token_urlsafe(6)[:8]}"


class ExperimentRepository:
    def __init__(self, db: Database):
        self.db = db

    # ---- writes ----

    def create(
        self,
        *,
        tenant_id: str,
        tenant_experiment_label: str,
        manifest_hash: str,
    ) -> Experiment:
        """Insert a new experiment in `submitted` state. Raises
        DuplicateExperimentLabelError if (tenant_id, label) already exists."""
        experiment_id = _generate_experiment_id()
        submitted_at = datetime.now(UTC).isoformat()
        try:
            self.db.execute(
                """
                INSERT INTO experiments (
                    experiment_id, tenant_id, tenant_experiment_label,
                    manifest_hash, status, submitted_at, revision
                ) VALUES (?, ?, ?, ?, ?, ?, 1)
                """,
                (
                    experiment_id,
                    tenant_id,
                    tenant_experiment_label,
                    manifest_hash,
                    ExperimentStatus.SUBMITTED.value,
                    submitted_at,
                ),
            )
        except sqlite3.IntegrityError as e:
            raise DuplicateExperimentLabelError(str(e)) from e
        got = self.get_by_id(experiment_id)
        assert got is not None
        return got

    def update_status(
        self,
        experiment_id: str,
        new_status: ExperimentStatus,
        *,
        expected_revision: int | None = None,
        error_summary: str | None = None,
        actor_class: CredentialClass | None = None,
    ) -> Experiment:
        """Transition an experiment's status. Enforces the allowed-transition
        graph + optional optimistic-concurrency check via `expected_revision`.

        `actor_class` (M6e) is recorded on the row as `last_action_by_class`
        for cross-role visibility. Existing callers may omit it; the column
        stays unchanged when not supplied.
        """
        current = self.get_by_id(experiment_id)
        if current is None:
            raise ExperimentNotFoundError(experiment_id)
        if expected_revision is not None and current.revision != expected_revision:
            raise InvalidStatusTransitionError(
                f"revision mismatch: expected {expected_revision}, got {current.revision}"
            )
        if new_status not in ALLOWED_TRANSITIONS[current.status]:
            raise InvalidStatusTransitionError(
                f"{current.status.value} → {new_status.value} is not an allowed transition"
            )

        # Side-effect timestamps.
        now = datetime.now(UTC).isoformat()
        set_started_at = current.started_at
        set_completed_at = current.completed_at
        if new_status is ExperimentStatus.APPROVED and current.started_at is None:
            set_started_at = datetime.fromisoformat(now)
        if (
            new_status
            in (
                ExperimentStatus.COMPLETED,
                ExperimentStatus.ABORTED,
            )
            and current.completed_at is None
        ):
            set_completed_at = datetime.fromisoformat(now)

        self.db.execute(
            """
            UPDATE experiments
            SET status = ?,
                started_at = ?,
                completed_at = ?,
                revision = revision + 1,
                error_summary = COALESCE(?, error_summary),
                last_action_at = ?,
                last_action_by_class = COALESCE(?, last_action_by_class)
            WHERE experiment_id = ?
            """,
            (
                new_status.value,
                set_started_at.isoformat() if set_started_at else None,
                set_completed_at.isoformat() if set_completed_at else None,
                error_summary,
                now,
                actor_class.value if actor_class is not None else None,
                experiment_id,
            ),
        )
        got = self.get_by_id(experiment_id)
        assert got is not None
        return got

    def finalize_submissions(
        self,
        experiment_id: str,
        *,
        actor_class: CredentialClass,
    ) -> Experiment:
        """Set `submissions_finalized=true` on the experiment.

        Idempotent: re-finalizing is a no-op (the flag stays true; last_action
        fields still update so audit trail shows the second attempt).

        Only the flag changes — status is unaffected. Auto-complete can then
        fire when all units complete; the work-units POST route rejects new
        submissions with 409. Raises ExperimentNotFoundError if the id is
        unknown.
        """
        current = self.get_by_id(experiment_id)
        if current is None:
            raise ExperimentNotFoundError(experiment_id)
        now = datetime.now(UTC).isoformat()
        self.db.execute(
            """
            UPDATE experiments
            SET submissions_finalized = 1,
                revision = revision + 1,
                last_action_at = ?,
                last_action_by_class = ?
            WHERE experiment_id = ?
            """,
            (now, actor_class.value, experiment_id),
        )
        got = self.get_by_id(experiment_id)
        assert got is not None
        return got

    def set_resource_bounds(
        self,
        experiment_id: str,
        *,
        max_unit_duration_seconds: int | None = None,
        max_units: int | None = None,
        max_concurrent_assignments: int | None = None,
        max_payload_bytes: int | None = None,
    ) -> Experiment:
        """Set resource bounds for an experiment. Called at approval time."""
        self.db.execute(
            """UPDATE experiments SET
                max_unit_duration_seconds = ?,
                max_units = ?,
                max_concurrent_assignments = ?,
                max_payload_bytes = ?
            WHERE experiment_id = ?""",
            (
                max_unit_duration_seconds,
                max_units,
                max_concurrent_assignments,
                max_payload_bytes,
                experiment_id,
            ),
        )
        got = self.get_by_id(experiment_id)
        if got is None:
            raise ExperimentNotFoundError(experiment_id)
        return got

    def set_integrity_policy(
        self,
        experiment_id: str,
        policy: IntegrityPolicy,
    ) -> Experiment:
        """Set the integrity policy for an experiment. Typically called at
        approval time by the Maintainer."""
        self.db.execute(
            "UPDATE experiments SET integrity_policy = ? WHERE experiment_id = ?",
            (policy.value, experiment_id),
        )
        got = self.get_by_id(experiment_id)
        if got is None:
            raise ExperimentNotFoundError(experiment_id)
        return got

    # ---- reads ----

    def get_by_id(self, experiment_id: str) -> Experiment | None:
        rows = self.db.execute(
            "SELECT * FROM experiments WHERE experiment_id = ?",
            (experiment_id,),
        )
        return self._row_to_experiment(rows[0]) if rows else None

    def list_all(
        self,
        *,
        tenant_id: str | None = None,
        status: ExperimentStatus | None = None,
    ) -> list[Experiment]:
        clauses: list[str] = []
        params: list[object] = []
        if tenant_id is not None:
            clauses.append("tenant_id = ?")
            params.append(tenant_id)
        if status is not None:
            clauses.append("status = ?")
            params.append(status.value)
        where = ("WHERE " + " AND ".join(clauses)) if clauses else ""
        rows = self.db.execute(
            f"SELECT * FROM experiments {where} ORDER BY submitted_at",
            tuple(params),
        )
        return [self._row_to_experiment(r) for r in rows]

    # ---- helpers ----

    @staticmethod
    def _row_to_experiment(row: sqlite3.Row) -> Experiment:
        return Experiment(
            experiment_id=row["experiment_id"],
            tenant_id=row["tenant_id"],
            tenant_experiment_label=row["tenant_experiment_label"],
            manifest_hash=row["manifest_hash"],
            status=ExperimentStatus(row["status"]),
            submitted_at=datetime.fromisoformat(row["submitted_at"]),
            started_at=datetime.fromisoformat(row["started_at"]) if row["started_at"] else None,
            completed_at=(
                datetime.fromisoformat(row["completed_at"]) if row["completed_at"] else None
            ),
            revision=row["revision"],
            error_summary=row["error_summary"],
            submissions_finalized=bool(row["submissions_finalized"]),
            last_action_at=(
                datetime.fromisoformat(row["last_action_at"]) if row["last_action_at"] else None
            ),
            last_action_by_class=(
                CredentialClass(row["last_action_by_class"])
                if row["last_action_by_class"]
                else None
            ),
            integrity_policy=IntegrityPolicy(row["integrity_policy"])
            if row["integrity_policy"]
            else IntegrityPolicy.STANDARD,
            max_unit_duration_seconds=row["max_unit_duration_seconds"],
            max_units=row["max_units"],
            max_concurrent_assignments=row["max_concurrent_assignments"],
            max_payload_bytes=row["max_payload_bytes"],
        )
